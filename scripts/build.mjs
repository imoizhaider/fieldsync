// Builds the static site into dist/.
//   * copies src/ as it is (plain HTML, CSS and ES modules, no framework)
//   * bundles Dexie and supabase-js into dist/js/vendor/ (no CDN at runtime)
//   * copies the IBM Plex Sans font files and writes the icons
//   * writes js/config.js with the Supabase URL and the public (anon) key only
//   * fills the service worker's file list and version
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, resolve } from 'node:path';
import { build } from 'esbuild';
import { loadEnv, ROOT } from './env.mjs';
import { iconPng } from './png.mjs';

const env = loadEnv();
const SRC = resolve(ROOT, 'src');
const DIST = resolve(ROOT, 'dist');

rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });
cpSync(SRC, DIST, { recursive: true });

// Vendored libraries, one ES module each.
for (const [name, entry, hasDefault] of [['dexie', 'dexie', true], ['supabase', '@supabase/supabase-js', false]]) {
  await build({
    stdin: {
      contents: `export * from '${entry}';${hasDefault ? ` export { default } from '${entry}';` : ''}`,
      resolveDir: ROOT, loader: 'js',
    },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true, legalComments: 'none',
    outfile: join(DIST, 'js/vendor', `${name}.js`), logLevel: 'error',
  });
}

// Fonts, bundled locally.
mkdirSync(join(DIST, 'fonts'), { recursive: true });
for (const weight of [400, 500, 600]) {
  const file = `ibm-plex-sans-latin-${weight}-normal.woff2`;
  cpSync(resolve(ROOT, 'node_modules/@fontsource/ibm-plex-sans/files', file), join(DIST, 'fonts', file));
}

// Icons.
mkdirSync(join(DIST, 'icons'), { recursive: true });
writeFileSync(join(DIST, 'icons/icon-192.png'), iconPng(192));
writeFileSync(join(DIST, 'icons/icon-512.png'), iconPng(512));
writeFileSync(join(DIST, 'icons/icon-maskable-512.png'), iconPng(512, { maskable: true }));
writeFileSync(join(DIST, 'icons/apple-touch-icon.png'), iconPng(180, { maskable: true }));

// Public configuration. The service key is never read here.
const url = env.SUPABASE_URL ?? '';
const anon = env.SUPABASE_ANON_KEY ?? '';
writeFileSync(join(DIST, 'js/config.js'),
  `// Generated by scripts/build.mjs. Public values only.\nexport const SUPABASE_URL = ${JSON.stringify(url)};\nexport const SUPABASE_ANON_KEY = ${JSON.stringify(anon)};\n`);
if (!url || !anon) console.warn('build: SUPABASE_URL / SUPABASE_ANON_KEY missing, the app will ask for configuration');

// GitHub Pages: do not run Jekyll over the output.
writeFileSync(join(DIST, '.nojekyll'), '');

// Service worker precache list and version.
function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const files = walk(DIST).map((p) => relative(DIST, p).replaceAll('\\', '/'))
  .filter((f) => f !== 'sw.js' && f !== '.nojekyll').sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);
const swPath = join(DIST, 'sw.js');
if (existsSync(swPath)) {
  writeFileSync(swPath, readFileSync(swPath, 'utf8')
    .replace("'__VERSION__'", JSON.stringify(version))
    .replace('__PRECACHE__', JSON.stringify(['./', ...files])));
}
console.log(`build: dist/ ready, ${files.length} files, version ${version}`);
